// Main dispatches an agent-facing subcommand and returns its exit status.
//
// The first argument decides the surface. `ftop` with no arguments still opens the
// TUI (main handles that before calling here), so this function is only reached for a
// subcommand.
func Main(args []string) int {
	return MainInto(os.Stdout, args)
}

// MainInto is Main with an explicit writer. The TUI uses it to capture a skill
// install's envelope without printing it into the alternate screen.
func MainInto(out io.Writer, args []string) int {
	io_ := IO{Out: out, Err: os.Stderr}
	if len(args) == 0 {
		return emitErr(io_.Out, "", usageErr("no subcommand"))
	}
	cmd, rest := args[0], args[1:]
	switch cmd {
	case "help", "-h", "--help":
		writeText(io_.Out, helpText)
		return ExitOK
	case "version":
		return runVersion(io_, rest)
	case "gpu":
		return runGPU(io_, rest)
	case "claim":
		// `ftop claim list` is a listing; `ftop claim` alone takes a card.
		if len(rest) > 0 && rest[0] == "list" {
			return runClaimList(io_, rest[1:])
		}
		return runClaim(io_, rest)
	case "release":
		return runRelease(io_, rest)
	case "renew":
		return runRenew(io_, rest)
	case "keep":
		return runKeep(io_, rest)
	case "whoami":
		return runWhoami(io_, rest)
	case "host":
		return runHost(io_, rest)
	case "skill":
		return runSkill(io_, rest)
	case "history":
		return runHistory(io_, rest)
	}
	return emitErr(io_.Out, cmd, usageErr("unknown subcommand %q; run `ftop help`", cmd))
}

// runVersion answers "what build am I talking to".
//
// It is its own subcommand rather than a proxy to main's -version flag: the proxy
// returned a sentinel that reached os.Exit as 255 with nothing on stdout, so an
// agent that asked got a failure and an empty string.
func runVersion(io_ IO, args []string) int {
	fs := newFlagSet("version", io_.Err)
	if err := parseFlags(fs, args); err != nil {
		return emitErr(io_.Out, "version", usageErr("%v", err))
	}
	emitOK(io_.Out, "version", map[string]any{
		"version": BuildVersion,
		// The skill is generated by this build; a stale one is a real problem, so the
		// answer to "what am I talking to" includes it.
		"skill": SkillSummary(),
		// api_version is what a script should branch on; version is for a human.
		"api_version": APIVersion,
	})
	return ExitOK
}

// runGPU dispatches `ftop gpu …`.
func runGPU(io_ IO, args []string) int {
	if len(args) == 0 {
		return emitErr(io_.Out, "gpu", usageErr("usage: ftop gpu list|show|why|history"))
	}
	sub, rest := args[0], args[1:]
	switch sub {
	case "list", "ls":
		return runGPUList(io_, rest)
	case "show":
		return runGPUShow(io_, rest)
	case "why", "who":
		return runGPUWhy(io_, rest)
	case "history":
		return runHistory(io_, rest)
	}
	return emitErr(io_.Out, "gpu", usageErr("unknown gpu subcommand %q", sub))
}

// runHistory implements `ftop history`.
func runHistory(io_ IO, args []string) int {
	fs := newFlagSet("history", io_.Err)
	limit := fs.Int("n", 20, "how many events")
	storeAt := fs.String("store", "", "ledger path")
	// parsePositional, not fs.Parse: `history GPU-0 -n 2` is the order a reader
	// writes, and Go's flag package stops at the first non-flag token. Parsing
	// plainly made `-n` a stray argument that was silently dropped, so the command
	// answered with the default 20 and looked correct.
	uuid, err := parsePositional(fs, args)
	if err != nil {
		return emitErr(io_.Out, "history", usageErr("%v", err))
	}
	s, err := ledger.Open(storePath(*storeAt))
	if err != nil {
		return emitErr(io_.Out, "history", classify(err))
	}
	defer s.Close()

	ev, err := s.History(uuid, *limit)
	if err != nil {
		return emitErr(io_.Out, "history", classify(err))
	}
	emitOK(io_.Out, "history", map[string]any{"events": ev, "count": len(ev)})
	return ExitOK
}

// runWhoami reports how ftop sees the caller.
//
// It exists because identity detection is inference: an agent that is about to claim
// a card should be able to see, in one call, exactly what will be recorded — and pass
// -as if the answer is wrong.
func runWhoami(io_ IO, args []string) int {
	fs := newFlagSet("whoami", io_.Err)
	if err := parseFlags(fs, args); err != nil {
		return emitErr(io_.Out, "whoami", usageErr("%v", err))
	}
	emitOK(io_.Out, "whoami", DetectIdentity())
	return ExitOK
}

// runHost lists the machines in the fleet.
//
// It reads the ssh configuration, not the ledger: an agent that needs a host name needs
// one before anything has been observed, and a machine with no cards in the ledger is
// still a machine it can be told to use. `ftop host` is therefore the JSON form of the
// TUI's `-list`, and the one command that answers "what are the machines called".
func runHost(io_ IO, args []string) int {
	fs := newFlagSet("host", io_.Err)
	storeAt := fs.String("store", "", "ledger path")
	cfgPath := fs.String("config", "", "config.toml path")
	if err := parseFlags(fs, args); err != nil {
		return emitErr(io_.Out, "host", usageErr("%v", err))
	}
	type hostRow struct {
		Host    string `json:"host"`
		Label   string `json:"label,omitempty"`
		Managed bool   `json:"managed"`
		// Manual hosts are never chosen by a claim that names no host.
		Manual bool `json:"manual,omitempty"`
		Cards  int  `json:"cards"`
		Free   int  `json:"free"`
		Held   int  `json:"held"`
	}
	rows := map[string]*hostRow{}
	var names []string
	row := func(name string) *hostRow {
		r, ok := rows[name]
		if !ok {
			r = &hostRow{Host: name}
			rows[name] = r
			names = append(names, name)
		}
		return r
	}

	// Every machine in the fleet, observed or not. This is the list an agent needs
	// before it has seen a single card: the names it may be told to work on.
	if cfg, err := config.Load(expandHome(*cfgPath)); err == nil {
		for _, h := range cfg.Hosts {
			r := row(h.Name)
			r.Label, r.Managed, r.Manual = h.Label, true, h.Manual
		}
	} else if *cfgPath != "" {
		return emitErr(io_.Out, "host", usageErr("%v", err))
	}

	// What the ledger knows, where it differs.
	if s, err := ledger.Open(storePath(*storeAt)); err == nil {
		if views, err := s.List(ledger.ListOptions{}); err == nil {
			for _, v := range views {
				r := row(v.Host)
				r.Cards++
				if v.Claim != nil {
					r.Held++
				} else {
					r.Free++
				}
			}
		}
		s.Close()
	}
	sort.Strings(names)
	out := make([]hostRow, 0, len(names))
	for _, n := range names {
		out = append(out, *rows[n])
	}
	emitOK(io_.Out, "host", map[string]any{"hosts": out, "count": len(out)})
	return ExitOK
}

// runSkill handles `ftop skill …`. Implemented in skill.go.
func runSkill(io_ IO, args []string) int { return skillCommand(io_, args) }

// helpText is the manual an agent reads once. It is deliberately short: an agent that
// has to read a long document to take a card will take it wrongly.
const helpText = `ftop — GPU fleet observation and claims

ftop never runs, stops or throttles anything. Agents run their own programs;
ftop records who holds which card and why, so the next agent can find out
before it starts.

  ftop                        open the live TUI
  ftop -list                  every machine, its label and hostname (text, not JSON)
  ftop gpu list [-host H] [-safe|-free|-held] [-no-ssh]
  ftop gpu show <uuid|host:index>
  ftop gpu why [-host H]      one line per card: who holds it, and why
  ftop claim -why "…" -for 2h [-n N|MIN..MAX] [-spread] [-min-vram MIB]
             [-exclude-host H] [-keep] [-directive "…"]
                              ftop chooses where: the closest fit, all or none.
                              MIN..MAX takes as many as are idle, at least MIN.
  ftop claim -host H -why "…" -for 2h [-n N]     on that machine
  ftop claim -gpu UUID -why "…" -for 2h [-adopt] that card
  ftop release <group|claim-id>
  ftop renew <group|claim-id> -for 4h
  ftop keep <group|claim-id> [-off]   keep it while idle, or stop keeping it
  ftop claim list [-mine]
  ftop history <gpu-uuid> [-n 20]
  ftop host                   every machine, its label, and its free cards
  ftop whoami                 how ftop identifies this session
  ftop skill install|status|uninstall
                              install the agent manual and point every agent at it

Every command prints JSON on stdout. Errors carry a stable "code"; exit status
3 means the cards are not there to take (held, busy, or too few) and
"conflicts" says by whom or how many.

Rules that matter:
  - let ftop choose the cards: it takes only cards it has just seen idle, and
    keeps whole machines free for jobs that need them. Release when done.
  - a claim whose card shows no work for 30 minutes is taken back before its
    deadline. Renew between jobs, or claim with -keep.
  - "gpu list -safe" lists what is free and idle; -free includes cards another
    job is already running on
  - if ftop cannot tell which agent you are, it refuses the claim: set FTOP_AGENT
    (and FTOP_SESSION) in your own instructions, or pass -as <name>
  - never take a card another agent holds; read the conflict and decide
  - a card the ledger calls free but the probe sees busy is someone's job
    started outside ftop: claim it with -gpu UUID -adopt if it is yours, or
    ask the operator; do not kill it
  - every machine in ~/.ssh/config is managed alike; leave one out with
    drop in config.toml, or keep claims off it unless named with
    [claim] manual
`

// indent is used by the skill renderer.
func indent(s string, n int) string {
	pad := strings.Repeat(" ", n)
	lines := strings.Split(s, "\n")
	for i := range lines {
		if lines[i] != "" {
			lines[i] = pad + lines[i]
		}
	}
	return strings.Join(lines, "\n")
}
